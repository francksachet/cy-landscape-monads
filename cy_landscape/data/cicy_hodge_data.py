def get_total_count():
    """Retourne le nombre total de CICY dans la base."""
    return sum(count for _, _, count in CICY_HODGE_PAIRS)


def get_mirror_extended_data():
    """
    Retourne les données avec variétés miroir (h11, h21) → (h21, h11).
    Les auto-miroir (h11 = h21) ne sont pas dupliquées.
    """
    extended = list(CICY_HODGE_PAIRS)
    existing = {(h, k) for h, k, _ in CICY_HODGE_PAIRS}
    for h11, h21, count in CICY_HODGE_PAIRS:
        if h11 != h21 and (h21, h11) not in existing:
            extended.append((h21, h11, count))
            existing.add((h21, h11))
    return extended
