"""
oxford_cicys.py -- Donnees CICY reelles du fichier d'Oxford (Candelas et al.)
Parsees a la main depuis cicylist.txt pour les entrees cles.

Format Oxford : lignes = espaces projectifs, colonnes = polynomes
Notre format  : config[a][r] = degre du polynome a dans l'espace r
=> Transposition necessaire.
"""
import numpy as np

def _make(num, ambient, oxford_rows, h11, h21, c2):
    """Construit un dict CICY a partir du format Oxford."""
    m = len(ambient)
    K = len(oxford_rows[0])
    mat = np.array(oxford_rows)  # m x K
    config = mat.T  # K x m
    return {
        "num": num, "ambient": ambient,
        "config": config, "h11": h11, "h21": h21,
        "chi": 2*(h11-h21), "c2": np.array(c2, dtype=float),
    }

